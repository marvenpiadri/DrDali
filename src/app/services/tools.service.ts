  // Evaluate symptoms logic
  evaluateSymptoms(selectedIds: string[]): SymptomAssessmentResult {
    if (!selectedIds.length) {
      return {
        matchedSymptoms: [],
        possibleCauses: [],
        urgencyLevel: 'Consultation programmée',
        urgencyColor: 'text-neutral-500',
        affectedAnatomy: [],
        actionsToDo: ['Sélectionnez au moins un symptôme pour générer une analyse éducative.'],
        actionsToAvoid: [],
        disclaimer: 'Ce module éducatif ne remplace aucun diagnostic clinique professionnel.',
      };
    }

    const hasLingeringHot = selectedIds.includes('sym-lingering-hot');
    const hasNightPain = selectedIds.includes('sym-night-pain');
    const hasSwelling = selectedIds.includes('sym-swelling');
    const hasBitingPain = selectedIds.includes('sym-chewing-pain');
    const hasBleeding = selectedIds.includes('sym-gum-bleeding');
    const hasLooseTooth = selectedIds.includes('sym-loose-tooth');
    const hasBrokenTooth = selectedIds.includes('sym-broken-tooth');
    const hasBadBreath = selectedIds.includes('sym-bad-breath');

    const causes: { condition: string; likelihood: 'Élevée' | 'Modérée' | 'Possible'; rationale: string; articleSlug?: string }[] = [];
    const affectedAnatomy: string[] = [];
    const actionsToDo: string[] = [];
    const actionsToAvoid: string[] = [];

    let urgency: 'Urgence immédiate' | 'Consultation prioritaire (24-48h)' | 'Consultation programmée' = 'Consultation programmée';
    let urgencyColor = 'text-emerald-700 dark:text-emerald-400';

    if (hasSwelling) {
      urgency = 'Urgence immédiate';
      urgencyColor = 'text-rose-700 dark:text-rose-400';
      causes.push({
        condition: 'Abcès dentaire d’origine pulpaire ou parodontale',
        likelihood: 'Élevée',
        rationale: 'Une tuméfaction de la gencive ou de la joue est le signe classique d’une collection infectieuse purulente active.',
        articleSlug: 'dental-abscess',
      });
      affectedAnatomy.push('Apex radiculaire', 'Os alvéolaire', 'Pulpe');
      actionsToDo.push('Consulter un chirurgien-dentiste sans attendre.', 'Maintenir la tête surélevée pour réduire la tension pulsatrice.');
      actionsToAvoid.push('Ne jamais appliquer de chaud sur la joue.', 'Ne pas prendre d’anti-inflammatoires (ibuprofène) sans prescription en cas d’abcès.');
    }

    if (hasNightPain || hasLingeringHot) {
      if (urgency !== 'Urgence immédiate') {
        urgency = 'Consultation prioritaire (24-48h)';
        urgencyColor = 'text-amber-700 dark:text-amber-400';
      }
      causes.push({
        condition: 'Pulpite aiguë irréversible (Rage de dent)',
        likelihood: 'Élevée',
        rationale: 'La douleur prolongée au chaud et les réveils nocturnes traduisent une congestion inflammatoire du nerf dentaire.',
        articleSlug: 'root-canal',
      });
      affectedAnatomy.push('Pulpe dentaire', 'Dentine');
      actionsToDo.push('Prendre du paracétamol selon la posologie autorisée en attendant la consultation.', 'Éviter toute sollicitation thermique de la zone.');
    }

    if (hasBitingPain) {
      causes.push({
        condition: 'Syndrome de la dent fêlée ou desmodontite apicale',
        likelihood: 'Modérée',
        rationale: 'La douleur survenant lors de la mastication oriente vers une fêlure de l’émail ou une inflammation du ligament de soutien.',
        articleSlug: 'tooth-pain',
      });
      affectedAnatomy.push('Émail', 'Ligament parodontal');
      actionsToAvoid.push('Éviter de mâcher des aliments durs ou croustillants du côté douloureux.');
    }

    if (hasBleeding || hasLooseTooth || hasBadBreath) {
      causes.push({
        condition: 'Gingivite ou Parodontite chronique (Atteinte des tissus de soutien)',
        likelihood: hasLooseTooth ? 'Élevée' : 'Modérée',
        rationale: 'Le saignement gingival répété combiné à la mobilité ou à une mauvaise haleine traduit une prolifération bactérienne sous-gingivale avec résorption osseuse potentielle.',
        articleSlug: 'periodontitis',
      });
      affectedAnatomy.push('Gencive', 'Os alvéolaire', 'Ligament parodontal');
      actionsToDo.push('Poursuivre un brossage méticuleux même si la gencive saigne (ne pas interrompre le nettoyage).', 'Utiliser des brossettes interdentaires de calibre adapté.');
      actionsToAvoid.push('Ne pas frotter avec une brosse à dents à poils durs qui aggraverait la rétraction.');
    }

    if (hasBrokenTooth) {
      if (urgency === 'Consultation programmée') {
        urgency = 'Consultation prioritaire (24-48h)';
        urgencyColor = 'text-amber-700 dark:text-amber-400';
      }
      causes.push({
        condition: 'Fracture coronaire amélo-dentinaire',
        likelihood: 'Élevée',
        rationale: 'La perte d’un pan dentaire expose la dentine sous-jacente aux bactéries et aux chocs thermiques.',
        articleSlug: 'dental-caries',
      });
      affectedAnatomy.push('Émail', 'Dentine');
    }

    // Deduplicate
    const uniqueAnatomy = Array.from(new Set(affectedAnatomy));
    if (!actionsToDo.length) {
      actionsToDo.push('Planifier une consultation d’évaluation clinique et radiologique au cabinet dentaire.');
    }

    return {
      matchedSymptoms: selectedIds,
      possibleCauses: causes,
      urgencyLevel: urgency,
      urgencyColor,
      affectedAnatomy: uniqueAnatomy,
      actionsToDo,
      actionsToAvoid,
      disclaimer: 'Attention : Ces éléments sont fournis à titre strictement informatif et indicatif. Seul un examen clinique complet avec radiographies réalisé par un praticien permet d’établir un diagnostic médical certain.',
    };
  }

  // Convert tooth numbers between notation systems
  convertNotation(fdi: number): { fdi: number; universal: number; palmer: string; name: string } | null {
    const tooth = this.allTeeth.find((t) => t.fdiNumber === fdi);
    if (!tooth) return null;
    return {
      fdi: tooth.fdiNumber,
      universal: tooth.universalNumber,
      palmer: tooth.palmerNotation,
      name: tooth.nameFr,
    };
  }
